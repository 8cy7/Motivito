// =============================================================
// الاختبار الثاني: دورة حياة رمز الدخول في التخزين
// =============================================================
//
// الهدف من هذا الاختبار:
// نتأكد إن بعد ما نحفظ رمز دخول الأب في الجهاز، نقدر نجيبه صح،
// وبعد تسجيل الخروج يُمسح ويصير فارغاً تماماً.
//
// ليش مهم؟
// رمز الدخول هو اللي يثبت هوية الأب للتطبيق.
// لو الحفظ ما شتغل صح، الأب يضطر يسجّل دخول كل مرة يفتح التطبيق.
// ولو المسح ما شتغل صح، أي شخص يقدر يدخل حساب الأب بدون إذن
// حتى بعد تسجيل الخروج، وهذي مشكلة أمنية خطيرة.
// =============================================================

// نستبدل مكتبة التخزين بنسخة وهمية لأن الاختبار يشتغل في الحاسوب
// وما عنده جهاز حقيقي يخزّن فيه البيانات
jest.mock('@react-native-async-storage/async-storage', () =>
  require('@react-native-async-storage/async-storage/jest/async-storage-mock')
);

import * as storage from '../../src/services/storage';

describe('دورة حياة رمز الدخول', () => {

  it('يحفظ رمز الدخول ويجيبه ثم يمسحه صح', async () => {
    // الخطوة الأولى: نحفظ رمز دخول وهمي
    await storage.saveParentTokens('رمز-وهمي-123', 'رمز-تجديد-456');

    // الخطوة الثانية: نجيب الرمز ونتحقق إنه نفس اللي حفظناه
    const token = await storage.getParentAccessToken();
    expect(token).toBe('رمز-وهمي-123');

    // الخطوة الثالثة: نمسح بيانات الأب (تسجيل خروج)
    await storage.clearParentData();

    // الخطوة الرابعة: نتحقق إن الرمز صار فارغاً بعد المسح
    const tokenAfterClear = await storage.getParentAccessToken();
    expect(tokenAfterClear).toBeNull();
  });

});
