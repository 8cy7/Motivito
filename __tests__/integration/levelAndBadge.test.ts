// =============================================================
// الاختبار الأول: المستوى والشارة معاً
// =============================================================
//
// الهدف من هذا الاختبار:
// نتأكد إن لما الطفل يكسب نقاط خبرة كافية للوصول للمستوى العاشر،
// شارته تتغير تلقائياً من النجمة العادية إلى النجم الساطع.
//
// ليش مهم؟
// اختبرنا حساب المستوى لحاله، واختبرنا الشارة لحالها.
// لكن ما اختبرنا إذا كانوا يتكلمون مع بعض صح.
// لو المستوى ارتفع بدون ما تتغير الشارة، الطفل ما يحس بالإنجاز
// ويصير خلل في التطبيق ما نلاحظه إلا لما يشتكي المستخدم.
// =============================================================

import { calculateLevelUp } from '../../src/utils/levelUtils';
import { shouldAwardNewBadge } from '../../src/utils/badgeUtils';

describe('المستوى والشارة معاً', () => {

  it('لما يكسب الطفل نقاط كافية لتجاوز المستوى التاسع، شارته تتغير', () => {
    const startLevel = 9;
    const startXP = 0;
    const earned = 1000;

    // الخطوة الأولى: نحسب المستوى الجديد بعد كسب النقاط
    const result = calculateLevelUp(startLevel, startXP, earned);

    // نتأكد إن المستوى ارتفع فعلاً
    expect(result.level).toBeGreaterThan(startLevel);

    // الخطوة الثانية: نتأكد إن الشارة تغيرت بين المستوى القديم والجديد
    const badgeChanged = shouldAwardNewBadge(startLevel, result.level, 'boy');
    expect(badgeChanged).toBe(true);
  });

});
